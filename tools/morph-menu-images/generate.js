/**
 * Writes _src/blocks/header/morph-menu-images.js: the banner (og:image) of every consumer page
 * linked from the dropdowns of the AEM mega menu, keyed by path without the locale.
 * Run with `node tools/morph-menu-images/generate.js` when the menu or the banners change.
 */
import { writeFile } from 'node:fs/promises';

const ORIGIN = 'https://www.bitdefender.com';
const MENU = `${ORIGIN}/content/experience-fragments/bitdefender/language_master/en/header-navigation/mega-menu/master/jcr:content/root.html`;
const OUT = new URL('../../_src/blocks/header/morph-menu-images.js', import.meta.url);
const CONCURRENCY = 6;

const decode = (value) => value.replaceAll('&#x26;', '&').replaceAll('&amp;', '&');

// same key as imageFor() in morph-menu.js
const keyOf = (pathname) => pathname
  .replace(/^\/[a-z]{2}-[a-z]{2}(?=\/)/i, '')
  .replace(/\/$/, '') || '/';

const menuLinks = (html) => {
  const links = new Set();
  [...html.matchAll(/<a\b[^>]*>/g)].forEach(([tag]) => {
    const classes = tag.match(/class="([^"]*)"/)?.[1].split(/\s+/) || [];
    const href = tag.match(/href="([^"]*)"/)?.[1];
    if (!href || !classes.includes('navigation__link')) return;
    const url = new URL(decode(href), ORIGIN);
    // consumer pages only; their og:image is the hero banner
    if (url.origin === ORIGIN && keyOf(url.pathname).startsWith('/consumer/')) links.add(url.pathname);
  });
  return [...links];
};

const bannerOf = async (pathname) => {
  const response = await fetch(`${ORIGIN}${pathname}`);
  if (!response.ok) return null;
  const html = await response.text();
  const content = html.match(/<meta[^>]+property="og:image"[^>]+content="([^"]+)"/)?.[1];
  if (!content) return null;
  const image = new URL(decode(content), ORIGIN);
  // Edge Delivery media: ask for a smaller, modern rendition
  if (image.pathname.includes('/media_')) image.search = '?width=750&format=webply&optimize=medium';
  return image.href;
};

const menu = await (await fetch(MENU)).text();
const queue = menuLinks(menu);
const images = {};
await Promise.all(Array.from({ length: CONCURRENCY }, async () => {
  while (queue.length) {
    const pathname = queue.shift();
    try {
      const image = await bannerOf(pathname);
      if (image) images[keyOf(pathname)] = image;
      else console.warn(`no og:image: ${pathname}`);
    } catch (error) {
      console.warn(`failed: ${pathname} ${error.message}`);
    }
  }
}));

const entries = Object.entries(images).sort(([a], [b]) => a.localeCompare(b));
await writeFile(OUT, `// generated by tools/morph-menu-images/generate.js, do not edit by hand
export default {
${entries.map(([key, image]) => `  '${key}': '${image}',\n`).join('')}};
`);
console.log(`${entries.length} images written to ${OUT.pathname}`);
